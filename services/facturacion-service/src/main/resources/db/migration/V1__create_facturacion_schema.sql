-- Esquema inicial de facturacion-service.

CREATE TABLE facturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_factura VARCHAR(50) NOT NULL,
    venta_id BIGINT NOT NULL,
    fecha_emision TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    cliente_id BIGINT NOT NULL,
    cliente_nombre VARCHAR(120) NOT NULL,
    cliente_email VARCHAR(150) NOT NULL,
    cliente_direccion VARCHAR(250) NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL,
    impuestos NUMERIC(12, 2) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'EMITIDA',
    CONSTRAINT idx_factura_numero UNIQUE (numero_factura),
    CONSTRAINT idx_factura_venta UNIQUE (venta_id)
);

CREATE TABLE factura_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    producto_nombre VARCHAR(150) NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12, 2) NOT NULL,
    subtotal_item NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_factura_items_factura
        FOREIGN KEY (factura_id) REFERENCES facturas (id) ON DELETE CASCADE
);

CREATE INDEX idx_factura_items_factura ON factura_items (factura_id);
