-- Esquema inicial de ventas-service.

CREATE TABLE ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_venta VARCHAR(50) NOT NULL,
    operacion_id VARCHAR(100) NOT NULL,
    cliente_id BIGINT NOT NULL,
    direccion_entrega VARCHAR(250) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    numero_factura VARCHAR(50),
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT idx_venta_numero UNIQUE (numero_venta),
    CONSTRAINT idx_venta_operacion UNIQUE (operacion_id)
);

CREATE INDEX idx_venta_cliente ON ventas (cliente_id);

CREATE TABLE venta_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    producto_nombre VARCHAR(150) NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12, 2) NOT NULL,
    subtotal_item NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_venta_items_venta
        FOREIGN KEY (venta_id) REFERENCES ventas (id) ON DELETE CASCADE
);

CREATE INDEX idx_venta_items_venta ON venta_items (venta_id);

CREATE TABLE solicitudes_tecnicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_solicitud VARCHAR(50) NOT NULL,
    cliente_id BIGINT NOT NULL,
    cliente_nombre VARCHAR(150) NOT NULL,
    cliente_telefono VARCHAR(50) NOT NULL,
    cliente_email VARCHAR(150) NOT NULL,
    servicio_tipo VARCHAR(80) NOT NULL,
    dispositivo_tipo VARCHAR(80) NOT NULL,
    marca_modelo VARCHAR(150) NOT NULL,
    sintomas TEXT NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'RECIBIDA',
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_solicitudes_numero UNIQUE (numero_solicitud)
);

CREATE INDEX idx_solicitudes_cliente_id ON solicitudes_tecnicas (cliente_id);
CREATE INDEX idx_solicitudes_estado ON solicitudes_tecnicas (estado);

CREATE TABLE conversaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_origen VARCHAR(30) NOT NULL,
    entidad_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    titulo_contexto VARCHAR(150) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ABIERTA',
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    fecha_ultima_actividad TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_conversacion_origen_entidad UNIQUE (tipo_origen, entidad_id)
);

CREATE INDEX idx_conversaciones_cliente_id ON conversaciones (cliente_id);

CREATE TABLE mensajes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id BIGINT NOT NULL,
    remitente_id BIGINT NOT NULL,
    remitente_rol VARCHAR(30) NOT NULL,
    remitente_nombre VARCHAR(150) NOT NULL,
    contenido TEXT NOT NULL,
    fecha_hora TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    leido_por_admin BOOLEAN NOT NULL DEFAULT FALSE,
    leido_por_cliente BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_mensajes_conversacion
        FOREIGN KEY (conversacion_id) REFERENCES conversaciones (id) ON DELETE CASCADE
);

CREATE INDEX idx_mensajes_conversacion_id ON mensajes (conversacion_id);
