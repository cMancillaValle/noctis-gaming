-- Esquema inicial de inventario-service.

CREATE TABLE inventario_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL,
    cantidad_disponible INTEGER NOT NULL,
    cantidad_reservada INTEGER NOT NULL DEFAULT 0,
    ubicacion_almacen VARCHAR(100),
    ultima_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_inventario_items_producto UNIQUE (producto_id)
);

CREATE TABLE movimientos_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion_id VARCHAR(100) NOT NULL,
    producto_id BIGINT NOT NULL,
    tipo_movimiento VARCHAR(40) NOT NULL,
    cantidad INTEGER NOT NULL,
    fecha TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    referencia VARCHAR(250)
);

CREATE INDEX idx_mov_operacion ON movimientos_inventario (operacion_id);
CREATE INDEX idx_mov_producto ON movimientos_inventario (producto_id);
